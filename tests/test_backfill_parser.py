"""
Tests for tools/backfill_file_logs.py's parse_log_line().

Golden lines are generated by actually running pathways/file_pathway.py's
FilePathway.send_alert() against a temp file, using the exact same `format`
string as data/config/docker.json's `file_log` pathway -- the only pathway
config docker-compose.yml actually references
(`command: [..., "--config", "/data/config/docker.json"]` for every
service). This exercises the real sanitize/format pipeline (newline
replacement, message truncation, whitespace collapsing) instead of a
hand-typed approximation of it, so these lines are genuinely representative
of what production writes, not a guess at it.

No live Postgres is used or needed here -- parse_log_line() is pure string
parsing.
"""

import sys
from pathlib import Path

_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_ROOT))                # pathways/ is a top-level package
sys.path.insert(0, str(_ROOT / "tools"))       # backfill_file_logs.py lives in tools/

from pathways.file_pathway import FilePathway  # noqa: E402
from backfill_file_logs import parse_log_line, VALID_LEVELS, VALID_CATEGORIES  # noqa: E402


# The exact format string from data/config/docker.json's file_log pathway.
DOCKER_FILE_LOG_FORMAT = "{timestamp} [{level}] [{category}] {source} [{client}]: {title} - {message}"


def _base_alert(**overrides) -> dict:
    alert = {
        "timestamp": 1735689600,  # 2025-01-01T00:00:00Z -- fixed, deterministic, 10 digits
        "level": "critical",
        "category": "system",
        "title": "Disk usage warning",
        "message": "Volume /data at 92% capacity",
        "source": "monitor-01",
        "client": "acmecorp",
    }
    alert.update(overrides)
    return alert


def _write_golden_line(tmp_path, alert, **pathway_overrides):
    """
    Run a real FilePathway.send_alert() against a temp file using the
    production `file_log` format/sanitization config, and return
    (line_without_trailing_newline, pathway_instance).
    """
    log_path = tmp_path / f"golden_{len(list(tmp_path.iterdir()))}.log"
    config = {
        "enabled": True,
        "path": str(log_path),
        "format": DOCKER_FILE_LOG_FORMAT,
        "create_directories": True,
        "append_mode": True,
        "sanitize_messages": True,
        "max_message_length": 500,
        "newline_replacement": " ↵ ",
    }
    config.update(pathway_overrides)
    pathway = FilePathway("file_log", config)

    ok = pathway.send_alert(alert)
    assert ok, "FilePathway.send_alert() failed to write the golden line"

    lines = log_path.read_text(encoding="utf-8").splitlines()
    assert len(lines) == 1, f"expected exactly one line, got {lines!r}"
    return lines[0], pathway


class TestGoldenLines:
    """The exact golden-line scenarios called for in the Task 13 brief."""

    def test_clientless_flat_file(self, tmp_path):
        """Flat file.log line (no client) -- real FilePathway writes an empty `[]` bracket."""
        alert = _base_alert(client="")
        line, _ = _write_golden_line(tmp_path, alert)

        assert "[]:" in line

        parsed = parse_log_line(line)
        assert parsed is not None
        assert parsed["client"] is None
        assert parsed["timestamp"] == 1735689600
        assert parsed["level"] == "critical"
        assert parsed["category"] == "system"
        assert parsed["source"] == "monitor-01"
        assert parsed["title"] == "Disk usage warning"
        assert parsed["message"] == "Volume /data at 92% capacity"

    def test_client_present_is_parsed_from_bracket(self, tmp_path):
        """
        Per-client line: the [client] bracket itself parses correctly.
        (The "folder name wins" override is the file-walker's job, not
        parse_log_line's -- covered in tests/test_backfill_db.py.)
        """
        alert = _base_alert(client="acmecorp")
        line, _ = _write_golden_line(tmp_path, alert)

        parsed = parse_log_line(line)
        assert parsed is not None
        assert parsed["client"] == "acmecorp"

    def test_newline_sanitization_artifact(self, tmp_path):
        """Multiline message gets FilePathway's real ' ↵ ' replacement, and still parses."""
        alert = _base_alert(message="Line one\nLine two\r\nLine three")
        line, _ = _write_golden_line(tmp_path, alert)

        assert " ↵ " in line

        parsed = parse_log_line(line)
        assert parsed is not None
        assert parsed["message"] == "Line one ↵ Line two ↵ Line three"

    def test_truncated_message(self, tmp_path):
        """
        Message over max_message_length (500) gets truncated by the real
        sanitizer to exactly 500 chars ending in '...'; verify parse_log_line
        recovers that exact truncated string, cross-checked against the
        real sanitize_for_single_line() output (not a hand-derived value).
        """
        long_message = "Disk usage climbing steadily past safe thresholds. " * 20
        assert len(long_message) > 500

        alert = _base_alert(message=long_message)
        line, pathway = _write_golden_line(tmp_path, alert)

        expected_message = pathway.sanitize_for_single_line(long_message, max_length=500)
        assert len(expected_message) == 500
        assert expected_message.endswith("...")

        parsed = parse_log_line(line)
        assert parsed is not None
        assert parsed["message"] == expected_message

    def test_brackets_in_title(self, tmp_path):
        """Title containing its own [brackets] must not confuse the client/title boundary."""
        alert = _base_alert(title="[URGENT] Server unreachable")
        line, _ = _write_golden_line(tmp_path, alert)

        parsed = parse_log_line(line)
        assert parsed is not None
        assert parsed["title"] == "[URGENT] Server unreachable"
        assert parsed["message"] == "Volume /data at 92% capacity"

    def test_spaces_in_source_field(self, tmp_path):
        """Multi-word source: internal single spaces preserved; sanitizer collapses runs."""
        alert = _base_alert(source="IT   Department West")  # extra spaces pre-sanitize
        line, _ = _write_golden_line(tmp_path, alert)

        parsed = parse_log_line(line)
        assert parsed is not None
        # sanitize_for_single_line collapses whitespace runs to a single space
        assert parsed["source"] == "IT Department West"

    def test_garbage_line_returns_none(self):
        assert parse_log_line("This is not a valid alert log line at all") is None

    def test_empty_line_returns_none(self):
        assert parse_log_line("") is None
        assert parse_log_line("\n") is None

    def test_truncated_mid_write_line_returns_none(self, tmp_path):
        """A line cut off before the ' - message' part (e.g. crash mid-write) is unparseable."""
        alert = _base_alert()
        line, _ = _write_golden_line(tmp_path, alert)
        # Simulate a line that got cut off before " - message"
        cutoff = line.split(" - ")[0]
        assert parse_log_line(cutoff) is None


class TestInvalidEnumValues:
    """
    FilePathway itself does not validate level/category -- it just formats
    whatever is in the alert dict (that validation happens upstream, at
    ingestion). A corrupted/legacy file could still contain a bad value, so
    the parser must defend against it independently. Generated the same way
    (through the real pathway) to stay consistent with the rest of this file.
    """

    def test_invalid_level_returns_none(self, tmp_path):
        alert = _base_alert(level="banana")
        line, _ = _write_golden_line(tmp_path, alert)
        assert parse_log_line(line) is None

    def test_invalid_category_returns_none(self, tmp_path):
        alert = _base_alert(category="banana")
        line, _ = _write_golden_line(tmp_path, alert)
        assert parse_log_line(line) is None

    def test_valid_level_alias_not_pre_normalized_is_rejected(self, tmp_path):
        """
        Level aliases (e.g. 'error' -> 'critical') are resolved upstream
        before the alert ever reaches FilePathway -- by the time a line is
        written, `level` is already canonical. A line with an alias instead
        of a canonical value is not something this parser is expected to
        normalize; verifying that documents the boundary explicitly.
        """
        alert = _base_alert(level="error")
        line, _ = _write_golden_line(tmp_path, alert)
        assert parse_log_line(line) is None


